_BY_CODE = {epic.code: epic for epic in EPICS}

UNSORTED_EPIC = Epic(
    code=UNSORTED,
    title="Не разобрано",
    emoji="📥",
    hint="эпик не определён — нужно решение человека",
    keywords=(),
)


def all_codes() -> list[str]:
    return [epic.code for epic in EPICS]


def get(code: str | None) -> Epic:
    """Эпик по коду. Неизвестный код — это `UNSORTED`, а не исключение:
    в базе могли остаться задачи со старым кодом после переименования, и
    падать на отображении доски из-за этого нельзя."""
    if not code:
        return UNSORTED_EPIC
    return _BY_CODE.get(code.strip().lower(), UNSORTED_EPIC)


def label(code: str | None) -> str:
    epic = get(code)
    return f"{epic.emoji} {epic.title}"


def _mentions(haystack: str, needle: str) -> bool:
    """Слово ищется с НАЧАЛА слова, а не где попало внутри.

    Без этого правила ловили мусор, и это не теория — проверено на реальной
    доске из 98 задач:

      «карточек»  содержало «чек»   → задача про анимацию уезжала в «Оплату»
      «вопросы»   содержало «опрос» → в «Исследования»
      «продумать» содержало «прод»  → в «Инфраструктуру»

    Неверный эпик хуже отсутствующего: он искажает картину приоритетов, на
    которую потом смотрят при планировании. Совпадение с начала слова окончания
    по-прежнему ловит («подключ» находит «подключение»), а середину чужого
    слова — уже нет.
    """
    return re.search(r"(?<![а-яa-z])" + re.escape(needle), haystack) is not None


def classify_by_keywords(text: str) -> str | None:
    """Эпик по ключевым словам. None — правила не сошлись.

    Считаем совпадения по каждому эпику и берём лучший. Если два эпика набрали
    одинаково — возвращаем None: неоднозначность лучше отдать модели или
    человеку, чем разрешить порядком объявления в списке.
    """
    haystack = text.lower().replace("ё", "е")
    scores: dict[str, int] = {}
    for epic in EPICS:
        hits = sum(1 for word in epic.keywords if _mentions(haystack, word.replace("ё", "е")))
        if hits:
            scores[epic.code] = hits
    if not scores:
        return None
    best = max(scores.values())
    winners = [code for code, hits in scores.items() if hits == best]
    if len(winners) > 1:
        return None
    return winners[0]


def classify(text: str, *, llm=None) -> str:
    """Эпик задачи: сначала правила, потом модель, потом «не разобрано».

    `llm` — объект с методом `chat` (см. `shared/llm_client.LLMClient`).
    None → работаем только правилами: классификация не должна требовать сети,
    иначе задача не создастся, когда модель недоступна.
    """
    by_rules = classify_by_keywords(text)
    if by_rules:
        return by_rules
    if llm is None:
        return UNSORTED
    return _classify_by_llm(text, llm)


def _classify_by_llm(text: str, llm) -> str:
    catalog = "\n".join(f"{epic.code} — {epic.title}: {epic.hint}" for epic in EPICS)
    prompt = (
        "Отнеси задачу команды к одному эпику. Ответь ТОЛЬКО кодом эпика, "
        "одним словом, без пояснений. Если задача не подходит ни к одному "
        f"или непонятна — ответь {UNSORTED}.\n\n"
        f"Эпики:\n{catalog}\n\n"
        f"Задача: {text.strip()[:500]}"
    )
    try:
        # max_tokens маленький намеренно: ответ — одно слово, и большой лимит
        # только провоцирует модель на рассуждения вместо кода эпика.
        answer = llm.chat(
            [{"role": "user", "content": prompt}], max_tokens=16, temperature=0.0
        )
    except Exception:
        # Классификация — удобство, а не условие создания задачи. Модель
        # недоступна → задача всё равно создаётся, просто без эпика.
        return UNSORTED
    code = (answer or "").strip().lower().strip(".,`\"'")
    return code if code in _BY_CODE else UNSORTED
