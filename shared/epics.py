"""Эпики: во что группируются задачи команды.

## Почему список закрытый, а не свободные теги

Свободные теги через месяц превращаются в сорок синонимов: «маркетинг»,
«marketing», «промо», «реклама», «продвижение» — и группировка перестаёт
работать именно тогда, когда задач стало много и она понадобилась. Поэтому
список фиксированный, и добавлять эпик — осознанное действие, а не побочный
эффект опечатки.

Восемь эпиков — это компромисс. Меньше пяти — всё сваливается в «прочее».
Больше десяти — человек не держит их в голове и выбирает наугад.

## Как задача попадает в эпик

Двумя способами, в этом порядке:

1. **По ключевым словам.** Дешево, предсказуемо, работает без сети и без денег.
   Ловит большинство: «баг», «лендинг», «промпт» не оставляют сомнений.
2. **Спросить модель.** Только если правила не сошлись. Один короткий запрос,
   ответ — одно слово из списка. Если модель ответила чем-то посторонним,
   считаем, что не определилось.

Не определилось — это НОРМАЛЬНЫЙ исход, а не ошибка. Задача попадает в
`UNSORTED`, и человек разберётся сам. Угадать неправильно хуже: неверный эпик
искажает картину приоритетов, на которую потом смотрят при планировании.
"""

