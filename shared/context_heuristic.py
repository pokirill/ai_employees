from __future__ import annotations

# R-COST: ключевые слова, при которых вопрос почти наверняка требует контекст
# проекта (Docs/*.md обоих репо — это ~сотни-тысячи токенов на каждый вызов).
# Без этой проверки контекст грузился бы и на "привет"/"спасибо", тратя
# бюджет впустую — а помощник задуман именно как ДЕШЁВЫЙ хелпер.
_PROJECT_KEYWORDS = (
    "кубышк", "архитектур", "бэклог", "беклог", "баг", "фича", "фичу", "релиз",
    "backend", "бэкенд", "бекенд", "ios", "апи", "api", "деплой", "deploy",
    "тест", "коммит", "ветк", "репо", "план", "задач", "приложен", "экран",
    "кнопк", "база данных", "миграц", "финассист", "finassist", "finik",
    "пуш", "уведомлен", "changelog", "чейнджлог",
)

# Достаточно длинный вопрос обычно содержательный, даже без явных ключевых
# слов из списка выше — простая эвристика-подстраховка.
_LENGTH_THRESHOLD = 60


def question_needs_project_context(text: str) -> bool:
    normalized = text.lower()
    if any(keyword in normalized for keyword in _PROJECT_KEYWORDS):
        return True
    return len(text.strip()) >= _LENGTH_THRESHOLD
